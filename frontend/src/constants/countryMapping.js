/**
 * Returns the short display name for a raw country name from the backend.
 * Falls back to the raw name if no mapping exists.
 *
 * @param {string} rawName - The formal country name from the API
 * @returns {string} - Short display name
 */
export function getCountryDisplayName(rawName) {
  return COUNTRY_MAPPING[rawName]?.displayName || rawName;
}

/**
 * Returns the ISO 3166-1 alpha-2 country code for a raw name.
 *
 * @param {string} rawName - The formal country name from the API
 * @returns {string|null} - Two-letter country code in lowercase or null
 */
export function getCountryCode(rawName) {
  const code = COUNTRY_MAPPING[rawName]?.code;
  return code ? code.toLowerCase() : null;
}
